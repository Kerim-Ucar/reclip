package com.kerim.reclip.platform.macos;

import java.lang.foreign.Arena;
import java.lang.foreign.FunctionDescriptor;
import java.lang.foreign.Linker;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.SymbolLookup;
import java.lang.foreign.ValueLayout;
import java.lang.invoke.MethodHandle;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.OptionalLong;
import java.util.Set;

/**
 * Lightweight macOS {@code NSPasteboard} bridge via Panama FFM to avoid AWT
 * {@code CClipboard} lock contention on large images and repeated polling.
 */
public final class MacOsPasteboard {

    private static final String PNG_UTI = "public.png";
    private static final String UTF8_TEXT_UTI = "public.utf8-plain-text";
    private static final Set<String> CONCEALED_PASTEBOARD_TYPES = Set.of(
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
            "com.apple.security.keychain-password");
    private static final Set<String> PASSWORD_MANAGER_IDENTIFIERS = Set.of(
            "com.apple.passwords",
            "com.apple.keychainaccess",
            "1password",
            "bitwarden",
            "keepassxc");

    private MacOsPasteboard() {
    }

    /**
     * Returns the current {@code NSPasteboard.generalPasteboard.changeCount}, or empty
     * if not running on macOS or if the native call fails.
     */
    public static OptionalLong changeCount() {
        if (!MacOsPermissions.isMacOs()) {
            return OptionalLong.empty();
        }
        try (Arena arena = Arena.ofConfined()) {
            ObjC objc = ObjC.load();
            MemorySegment pasteboard = objc.generalPasteboard(arena);
            if (pasteboard.equals(MemorySegment.NULL)) {
                return OptionalLong.empty();
            }
            long count = (long) objc.msgSendLong.invokeExact(pasteboard, objc.sel(arena, "changeCount"));
            return OptionalLong.of(count);
        } catch (Throwable ignored) {
            return OptionalLong.empty();
        }
    }

    /**
     * Returns whether {@code NSPasteboard.generalPasteboard} currently contains a
     * concealed/transient marker (used by password managers like 1Password, Bitwarden,
     * and macOS Passwords to keep secrets out of clipboard history).
     */
    public static boolean hasConcealedContent() {
        if (!MacOsPermissions.isMacOs()) {
            return false;
        }
        try (Arena arena = Arena.ofConfined()) {
            ObjC objc = ObjC.load();
            MemorySegment pasteboard = objc.generalPasteboard(arena);
            if (pasteboard.equals(MemorySegment.NULL)) {
                return false;
            }
            MemorySegment types = (MemorySegment) objc.msgSendObj.invokeExact(
                    pasteboard, objc.sel(arena, "types"));
            if (types.equals(MemorySegment.NULL)) {
                return false;
            }
            long count = (long) objc.msgSendLong.invokeExact(types, objc.sel(arena, "count"));
            MemorySegment objectAtIndexSel = objc.sel(arena, "objectAtIndex:");
            MemorySegment utf8Sel = objc.sel(arena, "UTF8String");
            for (long i = 0; i < count; i++) {
                MemorySegment nsType = (MemorySegment) objc.msgSendObjLong.invokeExact(types, objectAtIndexSel, i);
                if (nsType.equals(MemorySegment.NULL)) {
                    continue;
                }
                MemorySegment utf8Ptr = (MemorySegment) objc.msgSendObj.invokeExact(nsType, utf8Sel);
                if (!utf8Ptr.equals(MemorySegment.NULL)) {
                    String typeName = utf8Ptr.reinterpret(512).getString(0);
                    if (CONCEALED_PASTEBOARD_TYPES.contains(typeName)) {
                        return true;
                    }
                }
            }
            return false;
        } catch (Throwable ignored) {
            return false;
        }
    }

    /**
     * Returns whether the current frontmost macOS application matches any entry in
     * {@code excludedApps} (comparing localized app name and bundle identifier, case-insensitively).
     */
    public static boolean isFrontmostAppExcluded(List<String> excludedApps) {
        if (!MacOsPermissions.isMacOs() || excludedApps == null || excludedApps.isEmpty()) {
            return false;
        }
        List<String> identifiers = frontmostAppIdentifiers();
        if (identifiers.isEmpty()) {
            return false;
        }
        for (String excluded : excludedApps) {
            if (excluded == null || excluded.isBlank()) {
                continue;
            }
            String needle = excluded.trim().toLowerCase(Locale.ROOT);
            for (String id : identifiers) {
                if (id.toLowerCase(Locale.ROOT).contains(needle)) {
                    return true;
                }
            }
        }
        return false;
    }

    /**
     * Returns whether the frontmost macOS app is a known password manager
     * (used to mark entries as sensitive when the user un-excludes the app).
     */
    public static boolean isPasswordManagerFrontmost() {
        if (!MacOsPermissions.isMacOs()) {
            return false;
        }
        for (String id : frontmostAppIdentifiers()) {
            String lower = id.toLowerCase(Locale.ROOT);
            for (String marker : PASSWORD_MANAGER_IDENTIFIERS) {
                if (lower.contains(marker)) {
                    return true;
                }
            }
        }
        return false;
    }

    private static List<String> frontmostAppIdentifiers() {
        List<String> identifiers = new ArrayList<>(2);
        try (Arena arena = Arena.ofConfined()) {
            ObjC objc = ObjC.load();
            MemorySegment workspaceClass = objc.getClass(arena, "NSWorkspace");
            if (workspaceClass.equals(MemorySegment.NULL)) {
                return identifiers;
            }
            MemorySegment workspace = (MemorySegment) objc.msgSendObj.invokeExact(
                    workspaceClass, objc.sel(arena, "sharedWorkspace"));
            if (workspace.equals(MemorySegment.NULL)) {
                return identifiers;
            }
            MemorySegment frontApp = (MemorySegment) objc.msgSendObj.invokeExact(
                    workspace, objc.sel(arena, "frontmostApplication"));
            if (frontApp.equals(MemorySegment.NULL)) {
                return identifiers;
            }
            addNsStringProperty(objc, arena, frontApp, "localizedName", identifiers);
            addNsStringProperty(objc, arena, frontApp, "bundleIdentifier", identifiers);
        } catch (Throwable ignored) {
            // Best-effort frontmost app check.
        }
        return identifiers;
    }

    private static void addNsStringProperty(
            ObjC objc,
            Arena arena,
            MemorySegment target,
            String selectorName,
            List<String> out) throws Throwable {
        MemorySegment nsStr = (MemorySegment) objc.msgSendObj.invokeExact(target, objc.sel(arena, selectorName));
        if (!nsStr.equals(MemorySegment.NULL)) {
            MemorySegment utf8 = (MemorySegment) objc.msgSendObj.invokeExact(nsStr, objc.sel(arena, "UTF8String"));
            if (!utf8.equals(MemorySegment.NULL)) {
                String value = utf8.reinterpret(512).getString(0);
                if (!value.isBlank()) {
                    out.add(value);
                }
            }
        }
    }

    /**
     * Reads plain UTF-8 text directly from {@code NSPasteboard.generalPasteboard}
     * (useful when macOS apps like Passwords.app write pasteboard types that AWT
     * does not immediately surface as {@code stringFlavor}).
     */
    public static Optional<String> readPlainText() {
        if (!MacOsPermissions.isMacOs()) {
            return Optional.empty();
        }
        try (Arena arena = Arena.ofConfined()) {
            ObjC objc = ObjC.load();
            MemorySegment pasteboard = objc.generalPasteboard(arena);
            if (pasteboard.equals(MemorySegment.NULL)) {
                return Optional.empty();
            }
            MemorySegment utf8Type = objc.nsString(arena, UTF8_TEXT_UTI);
            MemorySegment nsText = (MemorySegment) objc.msgSendObjObj.invokeExact(
                    pasteboard, objc.sel(arena, "stringForType:"), utf8Type);
            if (nsText.equals(MemorySegment.NULL)) {
                MemorySegment legacyType = objc.nsString(arena, "NSStringPboardType");
                nsText = (MemorySegment) objc.msgSendObjObj.invokeExact(
                        pasteboard, objc.sel(arena, "stringForType:"), legacyType);
            }
            if (nsText.equals(MemorySegment.NULL)) {
                return Optional.empty();
            }
            MemorySegment utf8Ptr = (MemorySegment) objc.msgSendObj.invokeExact(
                    nsText, objc.sel(arena, "UTF8String"));
            if (utf8Ptr.equals(MemorySegment.NULL)) {
                return Optional.empty();
            }
            String text = utf8Ptr.reinterpret(1024 * 1024).getString(0);
            return text.isEmpty() ? Optional.empty() : Optional.of(text);
        } catch (Throwable ignored) {
            return Optional.empty();
        }
    }

    /**
     * Writes a PNG file directly to {@code NSPasteboard.generalPasteboard} without
     * decoding it through AWT {@code CClipboard}.
     *
     * @param pngFile path to an existing PNG file
     * @return {@code true} if the pasteboard accepted the PNG data
     */
    public static boolean writePngFile(Path pngFile) {
        if (!MacOsPermissions.isMacOs() || pngFile == null || !Files.isRegularFile(pngFile)) {
            return false;
        }
        try (Arena arena = Arena.ofConfined()) {
            ObjC objc = ObjC.load();
            MemorySegment pasteboard = objc.generalPasteboard(arena);
            if (pasteboard.equals(MemorySegment.NULL)) {
                return false;
            }
            MemorySegment nsPath = objc.nsString(arena, pngFile.toAbsolutePath().toString());
            MemorySegment nsDataClass = objc.getClass(arena, "NSData");
            MemorySegment nsData = (MemorySegment) objc.msgSendObjObj.invokeExact(
                    nsDataClass, objc.sel(arena, "dataWithContentsOfFile:"), nsPath);
            if (nsData.equals(MemorySegment.NULL)) {
                return false;
            }
            MemorySegment pngType = objc.nsString(arena, PNG_UTI);
            long ignored = (long) objc.msgSendLong.invokeExact(pasteboard, objc.sel(arena, "clearContents"));
            return (boolean) objc.msgSendBoolObjObj.invokeExact(
                    pasteboard, objc.sel(arena, "setData:forType:"), nsData, pngType);
        } catch (Throwable ignored) {
            return false;
        }
    }

    private record ObjC(
            MethodHandle objcGetClass,
            MethodHandle selRegisterName,
            MethodHandle msgSendObj,
            MethodHandle msgSendLong,
            MethodHandle msgSendObjLong,
            MethodHandle msgSendObjObj,
            MethodHandle msgSendBoolObjObj) {

        static ObjC load() {
            Linker linker = Linker.nativeLinker();
            SymbolLookup lookup = SymbolLookup.libraryLookup("/usr/lib/libobjc.A.dylib", Arena.global());
            MemorySegment msgSend = lookup.find("objc_msgSend").orElseThrow();
            return new ObjC(
                    linker.downcallHandle(lookup.find("objc_getClass").orElseThrow(),
                            FunctionDescriptor.of(ValueLayout.ADDRESS, ValueLayout.ADDRESS)),
                    linker.downcallHandle(lookup.find("sel_registerName").orElseThrow(),
                            FunctionDescriptor.of(ValueLayout.ADDRESS, ValueLayout.ADDRESS)),
                    linker.downcallHandle(msgSend,
                            FunctionDescriptor.of(ValueLayout.ADDRESS, ValueLayout.ADDRESS, ValueLayout.ADDRESS)),
                    linker.downcallHandle(msgSend,
                            FunctionDescriptor.of(ValueLayout.JAVA_LONG, ValueLayout.ADDRESS, ValueLayout.ADDRESS)),
                    linker.downcallHandle(msgSend,
                            FunctionDescriptor.of(ValueLayout.ADDRESS, ValueLayout.ADDRESS, ValueLayout.ADDRESS, ValueLayout.JAVA_LONG)),
                    linker.downcallHandle(msgSend,
                            FunctionDescriptor.of(ValueLayout.ADDRESS, ValueLayout.ADDRESS, ValueLayout.ADDRESS, ValueLayout.ADDRESS)),
                    linker.downcallHandle(msgSend,
                            FunctionDescriptor.of(ValueLayout.JAVA_BOOLEAN, ValueLayout.ADDRESS, ValueLayout.ADDRESS, ValueLayout.ADDRESS, ValueLayout.ADDRESS)));
        }

        MemorySegment getClass(Arena arena, String name) throws Throwable {
            return (MemorySegment) objcGetClass.invokeExact(arena.allocateFrom(name));
        }

        MemorySegment sel(Arena arena, String name) throws Throwable {
            return (MemorySegment) selRegisterName.invokeExact(arena.allocateFrom(name));
        }

        MemorySegment nsString(Arena arena, String value) throws Throwable {
            MemorySegment nsStringClass = getClass(arena, "NSString");
            return (MemorySegment) msgSendObjObj.invokeExact(
                    nsStringClass, sel(arena, "stringWithUTF8String:"), arena.allocateFrom(value));
        }

        MemorySegment generalPasteboard(Arena arena) throws Throwable {
            MemorySegment pasteboardClass = getClass(arena, "NSPasteboard");
            if (pasteboardClass.equals(MemorySegment.NULL)) {
                return MemorySegment.NULL;
            }
            return (MemorySegment) msgSendObj.invokeExact(pasteboardClass, sel(arena, "generalPasteboard"));
        }
    }
}
